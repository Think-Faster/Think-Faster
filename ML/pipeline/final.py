"""Шаг 20. Арифметика итоговой конфигурации (раздел 16 аналитики).

Числа не считаются заново: они сняты с `operating.py`, `cascade.py` и `factalert.py --mode
tradeoff` и сведены здесь в одну таблицу, чтобы суммы в аналитике нельзя было получить
опечаткой. Каждая строка помечена прогоном, на котором снята, — после раздела 24 база
сменилась с `main_h24_tuned` (4000 раундов) на `main_h24_tuned_r100e20` (100 раундов), и
старый столбец оставлен рядом, чтобы видеть, что из выигрыша дал бюджет, а что конфигурация.

    python final.py
"""
D = 181   # суток в тесте 2026 (янв–июн)
OBJ = 78

# тип: (сигналов, ложных, поймано с упреждением, всего эпизодов)
# «сейчас» — порог по лучшему F1, канала «по факту» нет.
old_f1 = {'пожар': (427, 279, 458, 603), 'загазованность': (75, 62, 26, 74),
          'подтопление': (18, 5, 32, 125), 'отказ оборудования': (761, 381, 1785, 2211),
          'отказ датчика': (517, 305, 557, 826), 'проникновение': (1, 1, 0, 92)}
new_f1 = {'пожар': (248, 115, 430, 603), 'загазованность': (75, 62, 26, 74),
          'подтопление': (12, 4, 21, 125), 'отказ оборудования': (560, 260, 1804, 2211),
          'отказ датчика': (517, 305, 557, 826), 'проникновение': (1, 1, 0, 92)}
# итоговая: пожар и подтопление — рабочий порог, оборудование — вторая ступень «сохранить 0,70»,
# датчик и загазованность — порог q90, проникновение выключено.
final = {'пожар': (248, 115, 430, 603), 'загазованность': (24, 9, 12, 74),
         'подтопление': (12, 4, 21, 125), 'отказ оборудования': (350, 122, 1619, 2211),
         'отказ датчика': (204, 54, 275, 826), 'проникновение': (0, 0, 0, 92)}

# после разделов 27-30: у каждого типа свой прогон и своя постобработка, выбранные по проверке
# 2025 (раздел 30), поверх — склейка дребезга 6 ч (раздел 27). Числа сняты с factalert.py
# --mode tradeoff при тех же правилах порога, что и строкой выше.
#   пожар          r12e4  + среднее 12 ч, рабочий порог
#   загазованность r12e4  + среднее 12 ч, порог q90
#   подтопление    r100e20,                рабочий порог
#   оборудование   r100e20 + среднее 6 ч,  рабочий порог
#   датчик         r12e4,                  порог q25 (выше шкала вырождается в ступеньку)
#   проникновение  выключено, работает только канал «по факту»
post = {'пожар': (113, 50, 394, 603), 'загазованность': (20, 10, 18, 74),
        'подтопление': (10, 2, 21, 125), 'отказ оборудования': (394, 159, 1784, 2211),
        'отказ датчика': (243, 119, 461, 826), 'проникновение': (0, 0, 0, 92)}

# после разделов 26 и 32: тот же протокол выбора, но в кандидатах ещё и вес класса 0,1 (раздел 26),
# а порог переносится долей, а не числом (раздел 32). Правила порога взяты те же, что строкой выше,
# иначе конфигурации нельзя было бы сравнить.
#   пожар          r12e4   + среднее 6 ч, рабочий порог
#   загазованность pw010   + среднее 6 ч, порог q90
#   подтопление    r100e20,                рабочий порог
#   оборудование   r100e20 + среднее 6 ч,  рабочий порог
#   датчик         pw010,                  порог q25
#   проникновение  pw010 — впервые не выключено, см. вариант ниже
post_pw = {'пожар': (118, 49, 409, 603), 'загазованность': (12, 6, 8, 74),
           'подтопление': (10, 2, 21, 125), 'отказ оборудования': (394, 159, 1784, 2211),
           'отказ датчика': (301, 149, 521, 826), 'проникновение': (0, 0, 0, 92)}
post_pw_intr = dict(post_pw, **{'проникновение': (287, 269, 92, 92)})

for tag, cfg, fact in (('сейчас, старая база main_h24_tuned (порог по F1, канала нет)', old_f1, False),
                       ('сейчас, короткий бюджет r100e20 (порог по F1, канала нет)', new_f1, False),
                       ('итоговая конфигурация раздела 16 (короткий бюджет + канал «по факту»)', final, True),
                       ('после разделов 27-30 (свой прогон на тип + склейка + сглаживание)', post, True),
                       ('после разделов 26 и 32 (то же плюс вес класса в кандидатах)', post_pw, True),
                       ('то же, но проникновение включено, а не отдано каналу «по факту»',
                        post_pw_intr, True)):
    s = sum(v[0] for v in cfg.values())
    f = sum(v[1] for v in cfg.values())
    c = sum(v[2] for v in cfg.values())
    e = sum(v[3] for v in cfg.values())
    byfact = e - c if fact else 0
    print(f'{tag}:')
    print(f'  сигналов прогноза {s} ({s / D:.1f}/сут), ложных {f} ({f / D:.2f}/сут, '
          f'{f / D / OBJ * 10:.3f} на объект за 10 сут)')
    print(f'  объявлено «по факту» {byfact} ({byfact / D:.1f}/сут), ложных на нём 0 по Н7/Н8')
    print(f'  эпизодов потеряно {0 if fact else e - c} из {e} | с упреждением {c} ({c / e:.1%})')
    print()

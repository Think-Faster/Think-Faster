"""Уверенность тревоги (INTEGRATION §2.1): сколько верить этой конкретной тревоге.

Имя модуля не `confidence` — в ML/pipeline/ уже есть confidence.py (калибровка на проверке), пути
обоих в sys.path, тень переезжала бы через неё. Калиброванный артефакт — изотоническая регрессия на
проверке 2025, `pipeline/confidence.py` (п. 1) — выгрузка работать не несёт, а строить его в такте
нечем. Поэтому здесь онлайн-приближение по трём носителям, которые видны из самого сообщения (пп.
3–5 того же скрипта), знак каждого подтверждён в аналитике:

- устойчивая тревога надёжнее разового всплеска — чем дольше стоит (`since_hours`), тем выше;
- согласие типов сильнее одиночного прогноза — сколько ещё типов тревожат тот же объект в тот же час;
- сработавшие каналы — след, оставленный реальностью: чем больше разных датчиков свежего окна, тем выше.

Числа мешаются с весами и только потом попадают в сообщение §2.3. Замена честная, но грубая: пока
выгрузка не принесёт калибровку, это мера-указатель, а не вероятность. Когда калибровка появится,
заменить здесь тело и тест, интерфейс не поменяется.
"""


def assurance(since_hours: int, neighbors: int, channels: int,
              since_cap_h: float = 24.0, agree_max: int = 5, chan_max: int = 3) -> float:
    """0..1 — приближение уверенности по трём носителям (см. шапку модуля).

    since_hours — сколько часов тревога уже стоит; neighbors — ещё сколько типов тревожат объект в
    тот же час; channels — разных датчиков свидетелей в свежем окне. Нижняя граница не нулевая:
    даже первый час тревоги — это сигнал, а не шум.
    """
    v_since = min(max(since_hours / since_cap_h, 0.0), 1.0)
    v_agree = min(max(neighbors / agree_max, 0.0), 1.0)
    v_chan = min(max(channels / chan_max, 0.0), 1.0)
    return float(min(max(0.10 + 0.35 * v_since + 0.30 * v_agree + 0.25 * v_chan, 0.0), 1.0))
import re
import numpy as np
import pandas as pd

# Трафарет для дат вида "02.04.2019 07:47:21" (с опциональным временем)
DATE_PATTERN = re.compile(r'^\d{2}\.\d{2}\.\d{4}( \d{2}:\d{2}:\d{2})?$')

def convert_sensor_types(df, source_col='значение_датчика'):
    """
    Классифицирует значение_датчика на числа / даты-артефакты / статусы.
    Исходный столбец source_col не изменяется - все результаты
    складываются в новые столбцы.
    """
    df = df.copy()
    raw = df[source_col].astype(str)

    is_date = raw.str.match(DATE_PATTERN)
    numeric = pd.to_numeric(raw, errors='coerce')
    is_numeric = numeric.notna() & ~is_date

    df['тип_значения'] = np.select(
        [is_date, is_numeric],
        ['date_artifact', 'numeric'],
        default='status'
    )

    df['значение_числовое'] = numeric.where(is_numeric)
    df['значение_dt'] = pd.to_datetime(raw.where(is_date), errors='coerce')
    df['значение_статус'] = raw.where(df['тип_значения'] == 'status').astype('category')

    print('Числовых:', is_numeric.sum())
    print('Дат-артефактов:', is_date.sum())
    print('Статусов:', (df['тип_значения'] == 'status').sum())

    return df


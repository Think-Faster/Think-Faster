def is_date(val):
  # 1. Проверка через встроенную конвертацию pandas (ловит почти любые типы дат и datetime)
  try:
    # Если строка/объект парсится в валидную дату — считаем датой
    pd.to_datetime(val)
    # Исключаем чистые числа, которые pandas может случайно попытаться распарсить
    if isinstance(val, (int, float)):
      return False
    # Исключаем строки, состоящие только из цифр (например, айдишники вроде "20231231")
    if str(val).isdigit():
      return False
    return True
  except (ValueError, TypeError):
    pass

  # 2. Дополнительные регулярные выражения для специфических текстовых форматов
  s = str(val).strip()
  date_patterns = [
      r'^\d{2}\.\d{2}\.\d{4}',  # 31.12.2023
      r'^\d{4}-\d{2}-\d{2}',  # 2023-12-31
      r'^\d{2}/\d{2}/\d{4}',  # 31/12/2023
      r'^\d{2}:\d{2}:\d{2}',  # 12:30:00
  ]

  for pattern in date_patterns:
    if re.match(pattern, s):
      return True

  return False


